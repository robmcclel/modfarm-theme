const fs = require('fs');
const {JSDOM} = require('jsdom');
const dom = new JSDOM(fs.readFileSync(process.argv[2], 'utf8'), {runScripts: 'outside-only'});
const win = dom.window;
const check = (ok, label) => { if (!ok) throw new Error(label); };
check(win.document.querySelectorAll('.mfw--tabs .mfw-section:not([hidden])').length === 4, 'No-JavaScript fallback hides content');
win.eval(fs.readFileSync('modfarm-theme/modfarm-theme/blocks/world/view.js', 'utf8'));
win.document.dispatchEvent(new win.Event('DOMContentLoaded'));
const roots = [...win.document.querySelectorAll('.mfw--tabs')];
const first = roots[0], second = roots[1];
const buttons = first.querySelectorAll('[role=tab]');
check(buttons.length === 2 && buttons[1].getAttribute('aria-selected') === 'true', 'Configured initial tab did not activate');
buttons[0].click(); check(buttons[0].getAttribute('aria-selected') === 'true', 'Click did not activate tab');
check(second.querySelectorAll('[role=tab]')[1].getAttribute('aria-selected') === 'true', 'Tab interaction crossed block instances');
buttons[0].dispatchEvent(new win.KeyboardEvent('keydown', {key: 'End', bubbles: true}));
check(win.document.activeElement === buttons[1] && buttons[1].getAttribute('aria-selected') === 'true', 'End key failed');
buttons[1].dispatchEvent(new win.KeyboardEvent('keydown', {key: 'ArrowRight', bubbles: true}));
check(win.document.activeElement === buttons[0], 'Arrow navigation did not wrap');
const ids = [...win.document.querySelectorAll('[id]')].map(node => node.id); check(ids.length === new Set(ids).size, 'Block instances duplicate IDs');
check(win.document.querySelectorAll('.mfw--sections [role=tab]').length === 0, 'Sections mode became tabs');
dom.window.close(); console.log('World tabs: passed');
