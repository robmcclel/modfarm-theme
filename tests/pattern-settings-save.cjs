const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('modfarm-theme/modfarm-theme/assets/js/modfarm-settings-ui.js', 'utf8');
const start = source.indexOf('  function syncPatternControls(');
const end = source.indexOf('\n  const tabs =', start);
const context = {};
vm.createContext(context);
vm.runInContext(source.slice(start, end), context);
const name = 'modfarm_theme_settings[archive_body_pattern_mf_offer]';
const visible = {tagName:'SELECT', name, value:'user/offers-archive'};
const hidden = {tagName:'SELECT', name, value:'default'};
const other = {tagName:'SELECT', name:'modfarm_theme_settings[archive_header_pattern]', value:'modfarm/header'};
const controls = [visible, hidden, other];
const form = {querySelectorAll:()=>controls};
context.syncPatternControls(form, visible);
assert.equal(hidden.value, visible.value);
assert.equal(other.value, 'modfarm/header');
hidden.value = 'modfarm-store/offers-archive';
context.syncPatternControls(form, hidden);
assert.equal(visible.value, hidden.value);
assert.equal(new URLSearchParams(controls.map(c=>[c.name,c.value])).getAll(name).every(v=>v===hidden.value), true);
context.syncPatternControls(form, {tagName:'INPUT',name,value:'ignore'});
assert.equal(visible.value, hidden.value);
assert.match(source, /addEventListener\('change', event => syncPatternControls\(form, event.target\), true\)/);
console.log('PASS: pattern selection survives duplicate form fields in either panel.');
